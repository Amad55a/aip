create table if not exists public.ai_requests (
  id uuid primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  usage_date date not null,
  context_type text not null check (context_type in ('lesson', 'project')),
  language text not null check (language in ('en', 'so', 'ar')),
  status text not null default 'pending' check (status in ('pending', 'succeeded', 'failed')),
  provider text check (provider in ('gemini', 'groq', 'openrouter')),
  model text,
  error_code text,
  response_time_ms integer check (response_time_ms is null or response_time_ms >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists ai_requests_user_date_idx
  on public.ai_requests (user_id, usage_date desc);

create table if not exists public.ai_provider_attempts (
  id bigint generated by default as identity primary key,
  request_id uuid not null references public.ai_requests (id) on delete cascade,
  provider text not null check (provider in ('gemini', 'groq', 'openrouter')),
  model text not null,
  status text not null check (status in ('succeeded', 'failed')),
  error_code text,
  response_time_ms integer not null check (response_time_ms >= 0),
  created_at timestamptz not null default now()
);

create index if not exists ai_provider_attempts_request_idx
  on public.ai_provider_attempts (request_id);

