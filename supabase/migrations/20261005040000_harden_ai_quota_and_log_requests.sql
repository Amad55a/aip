create or replace function public.get_ai_usage(p_daily_limit integer)
returns table (usage_date date, question_count integer, daily_limit integer, remaining_count integer)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
  today_utc date := timezone('utc', now())::date;
  used_count integer := 0;
begin
  if current_user_id is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;
  if p_daily_limit is distinct from 5 then
    raise exception 'Invalid AI daily limit' using errcode = '22023';
  end if;

  select coalesce((
    select au.question_count
    from public.ai_usage as au
    where au.user_id = current_user_id
      and au.usage_date = today_utc
  ), 0) into used_count;

  return query
  select today_utc, used_count, 5, greatest(5 - used_count, 0);
end;
$$;

