create or replace function public.reserve_ai_question(
  p_daily_limit integer,
  p_request_id uuid,
  p_context_type text,
  p_language text
)
returns table (
  request_id uuid,
  usage_date date,
  question_count integer,
  daily_limit integer,
  remaining_count integer,
  allowed boolean
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
#variable_conflict use_column
declare
  current_user_id uuid := auth.uid();
  today_utc date := timezone('utc', now())::date;
  used_count integer;
begin
  if current_user_id is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;
  if p_daily_limit is distinct from 5 or p_request_id is null then
    raise exception 'Invalid AI quota reservation' using errcode = '22023';
  end if;
  if p_context_type not in ('lesson', 'project') or p_language not in ('en', 'so', 'ar') then
    raise exception 'Invalid AI request context' using errcode = '22023';
  end if;

  insert into public.ai_usage as au (user_id, usage_date, question_count)
  values (current_user_id, today_utc, 1)
  on conflict (user_id, usage_date) do update
    set question_count = au.question_count + 1,
        updated_at = now()
    where au.question_count < p_daily_limit
  returning au.question_count into used_count;

  if used_count is null then
    select au.question_count into used_count
    from public.ai_usage as au
    where au.user_id = current_user_id
      and au.usage_date = today_utc;

    return query
    select null::uuid, today_utc, coalesce(used_count, 0), p_daily_limit,
      greatest(p_daily_limit - coalesce(used_count, 0), 0), false;
    return;
  end if;

  insert into public.ai_requests (id, user_id, usage_date, context_type, language)
  values (p_request_id, current_user_id, today_utc, p_context_type, p_language);

  return query
  select p_request_id, today_utc, used_count, p_daily_limit,
    greatest(p_daily_limit - used_count, 0), true;
end;
$$;

create or replace function public.finalize_ai_request(
  p_request_id uuid,
  p_status text,
  p_provider text,
  p_model text,
  p_error_code text,
  p_response_time_ms integer,
  p_attempts jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;
  if p_status not in ('succeeded', 'failed') or p_response_time_ms < 0 then
    raise exception 'Invalid AI request outcome' using errcode = '22023';
  end if;
  if p_provider is not null and p_provider not in ('gemini', 'groq', 'openrouter') then
    raise exception 'Invalid AI provider' using errcode = '22023';
  end if;
  if jsonb_typeof(coalesce(p_attempts, '[]'::jsonb)) <> 'array' then
    raise exception 'Invalid AI provider attempts' using errcode = '22023';
  end if;

  update public.ai_requests as request
  set status = p_status,
      provider = p_provider,
      model = p_model,
      error_code = p_error_code,
      response_time_ms = p_response_time_ms,
      updated_at = now()
  where request.id = p_request_id
    and request.user_id = current_user_id
    and request.status = 'pending';

  if not found then
    raise exception 'Pending AI request not found' using errcode = 'P0002';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(coalesce(p_attempts, '[]'::jsonb)) as attempt(
      provider text, model text, status text, error_code text, response_time_ms integer
    )
    where attempt.provider not in ('gemini', 'groq', 'openrouter')
       or attempt.status not in ('succeeded', 'failed')
       or attempt.response_time_ms is null
       or attempt.response_time_ms < 0
  ) then
    raise exception 'Invalid AI provider attempt data' using errcode = '22023';
  end if;

  insert into public.ai_provider_attempts (
    request_id, provider, model, status, error_code, response_time_ms
  )
  select
    p_request_id,
    attempt.provider,
    attempt.model,
    attempt.status,
    attempt.error_code,
    attempt.response_time_ms
  from jsonb_to_recordset(coalesce(p_attempts, '[]'::jsonb)) as attempt(
    provider text, model text, status text, error_code text, response_time_ms integer
  );

  return true;
end;
$$;

